#!/usr/bin/env python3
"""Generate native and optional companion snapshots from the canonical catalog."""
import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--app-root", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    doc = json.loads((ROOT / "src/beanfit/catalog/on_device.json").read_text())
    content = json.dumps(doc, indent=2, ensure_ascii=True)
    outputs = {ROOT / "iphone/BeanFitRuntime/ModelCatalog.generated.swift":
               '// Generated by scripts/sync_on_device_catalog.py; edit the canonical JSON.\n'
               'enum GeneratedModelCatalog {\n    static let json = #"""\n' + content + '\n"""#\n}\n'}
    if args.app_root:
        outputs[args.app_root / "src/lib/on-device-catalog.js"] = (
            '// Generated from beanfit src/beanfit/catalog/on_device.json.\n'
            'export const ON_DEVICE_CATALOG = ' + content + ';\n')
    stale = []
    for path, text in outputs.items():
        if args.check:
            if not path.exists() or path.read_text() != text:
                stale.append(str(path))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if stale:
        print("Stale catalog snapshots: " + ", ".join(stale), file=sys.stderr)
        return 1
    print("On-device catalog snapshots match" if args.check else "On-device catalog snapshots generated")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
